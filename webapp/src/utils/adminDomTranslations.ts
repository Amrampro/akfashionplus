const maps: Record<Exclude<Language, "fr">, TextMap> = { en, pt };
const textOriginals = new WeakMap<Text, string>();
const attrOriginals = new WeakMap<Element, Record<string, string>>();
const translatableAttrs = ["placeholder", "aria-label", "title"] as const;

function replacePreservingWhitespace(value: string, translated: string) {
  const prefix = value.match(/^\s*/)?.[0] || "";
  const suffix = value.match(/\s*$/)?.[0] || "";
  return `${prefix}${translated}${suffix}`;
}

function translateValue(value: string, language: Language) {
  if (language === "fr") return value;
  return maps[language]?.[value.trim()] || value;
}

export function translateAdminDom(root: ParentNode, language: Language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE"].includes(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      return node.textContent?.trim()
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_REJECT;
    },
  });

  const textNodes: Text[] = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode as Text);

  textNodes.forEach((node) => {
    const original = textOriginals.get(node) || node.textContent || "";
    textOriginals.set(node, original);
    const translated = translateValue(original, language);
    const nextText = replacePreservingWhitespace(original, translated);
    if (node.textContent !== nextText) node.textContent = nextText;
  });

  root.querySelectorAll?.("*").forEach((element) => {
    const originals = attrOriginals.get(element) || {};
    translatableAttrs.forEach((attr) => {
      const current = element.getAttribute(attr);
      if (!current) return;
      const original = originals[attr] || current;
      originals[attr] = original;
      const nextValue = replacePreservingWhitespace(
        original,
        translateValue(original, language),
      );
      if (current !== nextValue) element.setAttribute(attr, nextValue);
    });
    attrOriginals.set(element, originals);
  });
}
